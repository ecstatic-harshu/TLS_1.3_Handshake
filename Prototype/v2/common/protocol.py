import struct

from common.serializer import (
    encode,
    decode,
    MSG_HELLO,
    MSG_CIPHERTEXT,
    MSG_DSA_PUBKEY,
    MSG_SIGNATURE,
    MSG_DONE,
    MSG_ERROR
)


# =====================================
# PROTOCOL CONFIGURATION
# =====================================

NONCE_SIZE = 32

DONE_CONFIRMATION_SIZE = 32


# =====================================
# INTERNAL HELPERS
# =====================================

def _require_bytes(
    value,
    field_name,
    minimum_size=0
):
    """
    Validate that a protocol field is bytes.
    """

    if not isinstance(
        value,
        bytes
    ):
        raise TypeError(
            f"{field_name} must be bytes"
        )

    if len(value) < minimum_size:
        raise ValueError(
            f"{field_name} is too short"
        )

    return value


def _require_exact_size(
    value,
    field_name,
    expected_size
):
    """
    Validate exact byte length.
    """

    _require_bytes(
        value,
        field_name
    )

    if len(value) != expected_size:
        raise ValueError(
            f"{field_name} must be "
            f"{expected_size} bytes, "
            f"got {len(value)}"
        )

    return value


# =====================================
# HELLO
# =====================================
#
# Payload:
#
# | 32-byte client nonce |
# | 4-byte KEM public key length |
# | KEM public key |
#
# =====================================

def build_hello(
    nonce: bytes,
    kem_public_key: bytes
) -> bytes:

    _require_exact_size(
        nonce,
        "HELLO nonce",
        NONCE_SIZE
    )

    _require_bytes(
        kem_public_key,
        "KEM public key",
        minimum_size=1
    )

    payload = (
        nonce
        +
        struct.pack(
            ">I",
            len(kem_public_key)
        )
        +
        kem_public_key
    )

    return encode(
        MSG_HELLO,
        payload
    )


