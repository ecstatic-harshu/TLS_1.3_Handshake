# =====================================
# DONE
# =====================================
#
# Integrated format:
#
# | 32-byte PQ confirmation tag |
#
# The confirmation tag is generated by:
#
# HMAC-SHA256(
#     pq_shared_secret,
#     domain
#     || role
#     || auth_digest
#     || client_nonce
#     || server_nonce
# )
#
# =====================================

def build_done(
    confirmation: bytes
) -> bytes:

    _require_exact_size(
        confirmation,
        "DONE confirmation",
        DONE_CONFIRMATION_SIZE
    )

    return encode(
        MSG_DONE,
        confirmation
    )


# =====================================
# ERROR
# =====================================
#
# Payload:
#
# | UTF-8 encoded error message |
#
# =====================================

def build_error(
    message: str
) -> bytes:

    if not isinstance(
        message,
        str
    ):
        raise TypeError(
            "Error message must be str"
        )

    encoded_message = (
        message.encode(
            "utf-8"
        )
    )

    return encode(
        MSG_ERROR,
        encoded_message
    )


# =====================================
# PARSING HELPERS
# =====================================

def _parse_hello(
    payload: bytes
):
    """
    Parse HELLO payload.
    """

    minimum_size = (
        NONCE_SIZE
        +
        4
    )

    if len(payload) < minimum_size:
        raise ValueError(
            "Malformed HELLO payload"
        )

    nonce = payload[
        :NONCE_SIZE
    ]

    key_length = struct.unpack(
        ">I",
        payload[
            NONCE_SIZE:
            NONCE_SIZE + 4
        ]
    )[0]

    key_start = (
        NONCE_SIZE
        +
        4
    )

    key_end = (
        key_start
        +
        key_length
    )

    if key_length <= 0:
        raise ValueError(
            "Invalid KEM public key length"
        )

    if key_end != len(payload):
        raise ValueError(
            "HELLO KEM public key "
            "length mismatch"
        )

    kem_public_key = payload[
        key_start:
        key_end
    ]

    return {
        "nonce":
            nonce,

        "kem_public_key":
            kem_public_key
    }


def _parse_ciphertext(
    payload: bytes
):
    """
    Parse CIPHERTEXT payload.
    """

    minimum_size = (
        NONCE_SIZE
        +
        4
    )

    if len(payload) < minimum_size:
        raise ValueError(
            "Malformed CIPHERTEXT payload"
        )

    nonce = payload[
        :NONCE_SIZE
    ]

    ciphertext_length = struct.unpack(
        ">I",
        payload[
            NONCE_SIZE:
            NONCE_SIZE + 4
        ]
    )[0]

    ciphertext_start = (
        NONCE_SIZE
        +
        4
    )

    ciphertext_end = (
        ciphertext_start
        +
        ciphertext_length
    )

    if ciphertext_length <= 0:
        raise ValueError(
            "Invalid ciphertext length"
        )

    if ciphertext_end != len(payload):
        raise ValueError(
            "CIPHERTEXT length mismatch"
        )

    ciphertext = payload[
        ciphertext_start:
        ciphertext_end
    ]

    return {
        "nonce":
            nonce,

        "ciphertext":
            ciphertext
    }


def _parse_dsa_pubkey(
    payload: bytes
):
    """
    Parse DSA public key payload.
    """

    if len(payload) < 4:
        raise ValueError(
            "Malformed DSA_PUBKEY payload"
        )

    key_length = struct.unpack(
        ">I",
        payload[:4]
    )[0]

    if key_length <= 0:
        raise ValueError(
            "Invalid DSA public key length"
        )

    key_start = 4

    key_end = (
        key_start
        +
        key_length
    )

    if key_end != len(payload):
        raise ValueError(
            "DSA public key "
            "length mismatch"
        )

    dsa_public_key = payload[
        key_start:
        key_end
    ]

    return {
        "dsa_public_key":
            dsa_public_key
    }


def _parse_signature(
    payload: bytes
):
    """
    Parse signature payload.
    """

    if len(payload) < 4:
        raise ValueError(
            "Malformed SIGNATURE payload"
        )

    signature_length = struct.unpack(
        ">I",
        payload[:4]
    )[0]

    if signature_length <= 0:
        raise ValueError(
            "Invalid signature length"
        )

    signature_start = 4

    signature_end = (
        signature_start
        +
        signature_length
    )

    if signature_end != len(payload):
        raise ValueError(
            "SIGNATURE length mismatch"
        )

    signature = payload[
        signature_start:
        signature_end
    ]

    return {
        "signature":
            signature
    }


def _parse_done(
    payload: bytes
):
    """
    Parse DONE key-confirmation payload.
    """

    if len(payload) != DONE_CONFIRMATION_SIZE:
        raise ValueError(
            "DONE confirmation must be "
            f"{DONE_CONFIRMATION_SIZE} bytes, "
            f"got {len(payload)}"
        )

    return {
        "confirmation":
            payload,

        # Compatibility with your
        # handshake extraction helper.
        "payload":
            payload
    }


def _parse_error(
    payload: bytes
):
    """
    Parse UTF-8 error payload.
    """

    try:

        error_message = payload.decode(
            "utf-8"
        )

    except UnicodeDecodeError as exc:

        raise ValueError(
            "Malformed ERROR payload"
        ) from exc

    return {
        "error":
            error_message
    }


# =====================================
# MAIN PACKET PARSER
# =====================================

def parse_packet(
    raw_packet: bytes
):
    """
    Decode a protocol packet and return:

        (
            msg_type,
            fields
        )

    The outer serializer validates:
        - message type
        - payload length

    This function validates:
        - message-specific structure
        - exact field boundaries
        - required lengths
    """

    msg_type, payload = decode(
        raw_packet
    )

    # =====================================
    # HELLO
    # =====================================

    if msg_type == MSG_HELLO:

        fields = _parse_hello(
            payload
        )

    # =====================================
    # CIPHERTEXT
    # =====================================

    elif msg_type == MSG_CIPHERTEXT:

        fields = _parse_ciphertext(
            payload
        )

    # =====================================
    # DSA PUBLIC KEY
    # =====================================

    elif msg_type == MSG_DSA_PUBKEY:

        fields = _parse_dsa_pubkey(
            payload
        )

    # =====================================
    # SIGNATURE
    # =====================================

    elif msg_type == MSG_SIGNATURE:

        fields = _parse_signature(
            payload
        )

    # =====================================
    # DONE
    # =====================================

    elif msg_type == MSG_DONE:

        fields = _parse_done(
            payload
        )

    # =====================================
    # ERROR
    # =====================================

    elif msg_type == MSG_ERROR:

        fields = _parse_error(
            payload
        )

    # =====================================
    # DEFENSIVE FALLBACK
    # =====================================

    else:

        raise ValueError(
            f"Unsupported message type: "
            f"{msg_type:#04x}"
        )

    return (
        msg_type,
        fields
    )